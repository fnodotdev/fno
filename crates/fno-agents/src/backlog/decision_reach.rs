//! Reach: copies of a live decision where each harness reads its rules.
//!
//! A decision row may carry `reach: ["rules", "memory"]` beside the fno
//! store, which every row reaches. `rules` writes one line per decision into
//! a file every harness loads at session start. `memory` writes one file per
//! decision into Claude's auto memory for the decision's project. Every copy
//! carries the decision id, so [`sync`] rewrites the whole set from the live
//! store and a decision that expires, retires or is retracted loses every
//! copy on the next sync. Nothing else writes these copies.
//!
//! A static file cannot test a session fact, so a row with any filter is
//! refused rules and memory reach at the door; `--at-skill` delivers it.

use serde_json::Value;
use std::path::{Path, PathBuf};

/// The reach values a door accepts. `store` is implicit on every row.
pub const REACH: &[&str] = &["store", "rules", "memory"];

const BEGIN: &str = "<!-- fno:decisions begin: generated by fno, do not edit -->";
const END: &str = "<!-- fno:decisions end -->";
/// The file name fno owns outright in a rules directory.
const RULES_FILE: &str = "fno-decisions.md";
/// The memory file prefix; the sweep deletes only names it wrote.
const MEMORY_PREFIX: &str = "fno-decision-";

fn s<'a>(row: &'a Value, key: &str) -> &'a str {
    row.get(key).and_then(Value::as_str).unwrap_or("")
}

fn reaches(row: &Value, layer: &str) -> bool {
    #[derive(Default, serde::Deserialize)]
    #[serde(default)]
    struct Reach {
        reach: Vec<String>,
    }
    let reach: Reach = serde::Deserialize::deserialize(row).unwrap_or_default();
    reach.reach.iter().any(|r| r == layer)
}

/// Parse `--reach store,rules,memory`, refusing a filtered row the static
/// layers, which cannot test a session fact.
pub fn parse_reach(
    spec: &str,
    filtered: bool,
) -> Result<Vec<String>, crate::decision_index::SpecError> {
    use crate::decision_index::SpecError;
    let mut out = Vec::new();
    for part in spec.split(',').map(str::trim).filter(|p| !p.is_empty()) {
        if !REACH.contains(&part) {
            return Err(SpecError(format!(
                "--reach takes {}, not {part:?}",
                REACH.join(", ")
            )));
        }
        if part != "store" && filtered {
            return Err(SpecError(format!(
                "--reach {part} copies the decision into a file every session reads, and a file \
cannot test a filter. Use --at-skill <skill> to deliver a filtered decision"
            )));
        }
        if !out.iter().any(|o: &String| o == part) {
            out.push(part.to_string());
        }
    }
    Ok(out)
}

/// One line per decision, the D number first when the row has one.
fn line(row: &Value, numbers: &std::collections::HashMap<String, String>) -> String {
    let id = s(row, "decision_id");
    let label = numbers
        .get(&id.to_lowercase())
        .map(|n| format!("{n} ({id})"))
        .unwrap_or_else(|| id.to_string());
    let text = crate::law_match::one_line(s(row, "decision"), 400);
    format!("- {label}, {}: {text}", s(row, "subject"))
}

/// The rules locations under a home dir: an fno-owned file where the
/// harness reads a directory, an fno-owned block where it reads one shared
/// file. Never `~/.codex/rules`, which is codex exec policy.
fn rules_targets(home: &Path) -> Vec<(PathBuf, bool)> {
    vec![
        (home.join(".claude/rules").join(RULES_FILE), true),
        (home.join(".codex/AGENTS.md"), false),
        (home.join(".config/opencode/AGENTS.md"), false),
        (home.join(".gemini/GEMINI.md"), false),
    ]
}

/// Replace, add or remove the fno block in a shared file's text.
fn with_block(text: &str, body: &str) -> String {
    let kept = match (text.find(BEGIN), text.find(END)) {
        (Some(a), Some(b)) if b > a => {
            format!(
                "{}{}",
                &text[..a],
                text[b + END.len()..].trim_start_matches('\n')
            )
        }
        _ => text.to_string(),
    };
    let kept = kept.trim_end_matches('\n');
    if body.is_empty() {
        return if kept.is_empty() {
            String::new()
        } else {
            format!("{kept}\n")
        };
    }
    let sep = if kept.is_empty() { "" } else { "\n\n" };
    format!("{kept}{sep}{BEGIN}\n{body}\n{END}\n")
}

/// What one sync changed.
#[derive(Debug, Default, PartialEq)]
pub struct Synced {
    pub written: Vec<PathBuf>,
    pub removed: Vec<PathBuf>,
}

/// Rewrite every copy from the live rows under `home`. A rules file or
/// block holds exactly the live `rules` rows; a memory dir holds exactly
/// the live `memory` rows of its project. A shared file is created only
/// when there is something to write and its harness's config dir exists.
pub fn sync_at(
    home: &Path,
    live: &[Value],
    numbers: &std::collections::HashMap<String, String>,
    memory_dir_of: &dyn Fn(&str) -> Option<PathBuf>,
) -> Synced {
    let mut out = Synced::default();
    let body: Vec<String> = live
        .iter()
        .filter(|r| reaches(r, "rules"))
        .map(|r| line(r, numbers))
        .collect();
    let body = body.join("\n");
    for (path, owned) in rules_targets(home) {
        let old = std::fs::read_to_string(&path).unwrap_or_default();
        if owned {
            if body.is_empty() {
                if path.exists() && std::fs::remove_file(&path).is_ok() {
                    out.removed.push(path);
                }
                continue;
            }
            let new = format!("# Standing decisions\n\n{BEGIN}\n{body}\n{END}\n");
            if new != old && write(&path, &new) {
                out.written.push(path);
            }
            continue;
        }
        // A harness that is not installed has no config dir; fno never
        // makes one for it.
        if !path.parent().is_some_and(Path::is_dir) || (body.is_empty() && !old.contains(BEGIN)) {
            continue;
        }
        let new = with_block(&old, &body);
        if new != old && write(&path, &new) {
            out.written.push(path);
        }
    }
    // Memory: one file per live row, under its project's memory dir.
    let mut wanted: std::collections::BTreeMap<PathBuf, Vec<&Value>> = Default::default();
    for row in live.iter().filter(|r| reaches(r, "memory")) {
        let scope = crate::decision_index::row_scope(row);
        if let Some(dir) = scope.strip_prefix("project:").and_then(memory_dir_of) {
            wanted.entry(dir).or_default().push(row);
        }
    }
    let mut dirs: std::collections::BTreeSet<PathBuf> = wanted.keys().cloned().collect();
    dirs.extend(known_memory_dirs(home));
    for dir in dirs {
        let rows = wanted.get(&dir).cloned().unwrap_or_default();
        let keep: std::collections::BTreeSet<String> = rows
            .iter()
            .map(|r| format!("{MEMORY_PREFIX}{}.md", s(r, "decision_id")))
            .collect();
        for row in rows {
            let id = s(row, "decision_id");
            let path = dir.join(format!("{MEMORY_PREFIX}{id}.md"));
            let text = format!(
                "---\nname: {MEMORY_PREFIX}{id}\ndescription: {}\nmetadata:\n  type: feedback\n  fno_decision: {id}\n---\n\n{}\n",
                // A JSON string is a valid YAML scalar, and the line holds `: `.
                serde_json::json!(format!(
                    "fno decision {}",
                    line(row, numbers).trim_start_matches("- ")
                )),
                s(row, "decision")
            );
            if std::fs::read_to_string(&path).ok().as_deref() != Some(&text) && write(&path, &text)
            {
                out.written.push(path);
            }
        }
        let Ok(entries) = std::fs::read_dir(&dir) else {
            continue;
        };
        for entry in entries.filter_map(Result::ok) {
            let name = entry.file_name().to_string_lossy().into_owned();
            if name.starts_with(MEMORY_PREFIX) && name.ends_with(".md") && !keep.contains(&name) {
                if std::fs::remove_file(entry.path()).is_ok() {
                    out.removed.push(entry.path());
                }
            }
        }
    }
    out
}

/// Claude memory dirs that already hold an fno copy, so the sweep finds a
/// copy whose decision left the live set.
fn known_memory_dirs(home: &Path) -> Vec<PathBuf> {
    let Ok(projects) = std::fs::read_dir(home.join(".claude/projects")) else {
        return Vec::new();
    };
    projects
        .filter_map(Result::ok)
        .map(|p| p.path().join("memory"))
        .filter(|dir| {
            std::fs::read_dir(dir).is_ok_and(|mut e| {
                e.any(|f| {
                    f.ok()
                        .is_some_and(|f| f.file_name().to_string_lossy().starts_with(MEMORY_PREFIX))
                })
            })
        })
        .collect()
}

fn write(path: &Path, text: &str) -> bool {
    if let Some(parent) = path.parent() {
        if std::fs::create_dir_all(parent).is_err() {
            return false;
        }
    }
    std::fs::write(path, text).is_ok()
}

/// Claude's auto memory dir for a project root: the root path with every
/// `/` turned into `-`, under `~/.claude/projects`.
fn claude_memory_dir(home: &Path, root: &Path) -> PathBuf {
    let slug = root.to_string_lossy().replace(['/', '.'], "-");
    home.join(".claude/projects").join(slug).join("memory")
}

/// Sync every copy on this machine from the live store. Best effort: a
/// copy that cannot be written stays as it was, and the next sync retries.
pub fn sync() -> Synced {
    let Some(home) = std::env::var_os("HOME").map(PathBuf::from) else {
        return Synced::default();
    };
    // A door test reaches here through the log refresh; it must never
    // rewrite the developer's own rules files or memory.
    if cfg!(test) && !crate::paths::under_temp_dir(&home) {
        return Synced::default();
    }
    let Ok(index) = crate::decision_index::default_store_live() else {
        return Synced::default();
    };
    let numbers = crate::numbers::labels();
    let memory_dir_of = |project: &str| {
        crate::backlog::settings::project_root(project)
            .map(|root| claude_memory_dir(&home, Path::new(&root)))
    };
    sync_at(&home, &index.rows, &numbers, &memory_dir_of)
}

#[cfg(test)]
mod tests {
    use super::*;
    use serde_json::json;

    #[test]
    fn a_sync_writes_one_marked_copy_per_layer_and_the_next_sync_removes_it() {
        let home = tempfile::tempdir().expect("tempdir");
        let codex = home.path().join(".codex/AGENTS.md");
        std::fs::create_dir_all(codex.parent().unwrap()).unwrap();
        std::fs::write(&codex, "# mine\n\nkeep this\n").unwrap();
        let memory = home.path().join(".claude/projects/-demo/memory");
        let row = json!({
            "decision_id": "d-0000c0de",
            "subject": "release-merges",
            "decision": "Squash-only PRs toward 0.5.0.",
            "scope": "project:demo",
            "reach": ["rules", "memory"],
        });
        let numbers =
            std::collections::HashMap::from([("d-0000c0de".to_string(), "D9".to_string())]);
        let dir_of = |p: &str| (p == "demo").then(|| memory.clone());
        let first = sync_at(home.path(), std::slice::from_ref(&row), &numbers, &dir_of);
        let claude = home.path().join(".claude/rules").join(RULES_FILE);
        assert!(std::fs::read_to_string(&claude)
            .unwrap()
            .contains("D9 (d-0000c0de)"));
        let shared = std::fs::read_to_string(&codex).unwrap();
        assert!(shared.starts_with("# mine\n\nkeep this\n") && shared.contains("D9 (d-0000c0de)"));
        let copy = memory.join("fno-decision-d-0000c0de.md");
        assert!(std::fs::read_to_string(&copy)
            .unwrap()
            .contains("fno_decision: d-0000c0de"));
        assert!(
            !home.path().join(".gemini/GEMINI.md").exists(),
            "no empty file is made"
        );
        assert_eq!(first.written.len(), 3, "{first:?}");
        // AC6: the decision leaves the live set, every copy goes.
        let second = sync_at(home.path(), &[], &numbers, &|_| None);
        assert!(!claude.exists());
        assert_eq!(
            std::fs::read_to_string(&codex).unwrap(),
            "# mine\n\nkeep this\n"
        );
        assert!(second.removed.contains(&claude));
        assert!(!copy.exists(), "the sweep finds a memory copy no row names");
        let third = sync_at(home.path(), &[], &numbers, &|_| None);
        assert_eq!(third, Synced::default(), "a second sync changes nothing");
        assert!(
            parse_reach("rules", true).is_err(),
            "a filtered row cannot reach a file"
        );
        assert_eq!(
            parse_reach("store,rules,rules", false).unwrap(),
            ["store", "rules"]
        );
    }
}
