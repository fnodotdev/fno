#!/usr/bin/env python3
"""Build-free regen for the config-schema doc rows and their parity goldens.

generated-artifacts.tsv rows for docs/configuration-guide.md,
docs/config.example.toml and crates/fno/config.example.toml regenerate with
`fno config schema --toml/--markdown --write`, but the schema table is
include_str!'d at compile time: only a binary built from the edited tables
renders the new rows, and a session under a build freeze cannot build one.
This script reproduces the four renderers in src/config/config_schema.rs byte
for byte (that file is itself a byte-for-byte port of python json.dumps),
proves itself against the committed artifacts, and writes. CI's parity step
stays the proof, same contract as scripts/regen-generated-copies.py.

--validate  render the pre-edit table (origin/main) and require every output
            to byte-match the committed goldens and generated files.
--write     render the worktree table and write the goldens and generated
            files. Refuses to run until --validate has passed.
"""

import argparse
import json
import subprocess
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
TABLE = ROOT / "crates/fno/config_schema.json"
GOLDENS = ROOT / "crates/fno/tests/golden/config_schema"

MARKDOWN_HEADER = (
    "# Configuration reference",
    "",
    "> Generated by `fno config schema --markdown` from the hand-owned schema tables (`crates/fno/src/config/config_cli/model/fields.json` + `crates/fno/config_schema.json`). Do not edit by hand; edit the tables and keep the table-agreement test green.",
    "",
    "Keys live in a flat `config.toml` (`.fno/config.toml` project-local, `~/.fno/config.toml` global). A dotted key like `branch.prefix` is `prefix` under `[branch]`. For a copy-paste template with every key at its default, see [config.example.toml](config.example.toml); read or set individual keys with `fno config get <key>` / `fno config set <key> <value>`.",
    "",
    "| Key | Type | Default | Wizard | Description |",
    "|-----|------|---------|--------|-------------|",
)

TOML_HEADER = (
    "# footnote config reference (config.example.toml)",
    "#",
    "# Generated by `fno config schema --toml` from the hand-owned schema tables",
    "# (fields.json + config_schema.json). Do not edit by hand; edit the tables",
    "# and keep the table-agreement test green.",
    "#",
    "# Every key is shown set to its DEFAULT. Copy the keys you want to change",
    "# into .fno/config.toml (project-local) or ~/.fno/config.toml (global);",
    "# anything you omit falls back to these defaults. config.toml is flat:",
    "# top-level scalars and [blocks], no wrapper. Optional keys with no",
    "# default are shown commented out (TOML has no null).",
    "#",
    "# For opinionated starters (recommended values, safe opt-ins on), see",
    "# docs/config.global.example.toml and docs/config.local.example.toml.",
    "",
)


def py_str(s):
    return json.dumps(s, ensure_ascii=True)


def py_compact(v):
    return json.dumps(v, ensure_ascii=True)


def cell(text):
    return text.replace("|", "\\|")


def fmt_default(v):
    if v is None:
        return "_(none)_"
    if isinstance(v, bool):
        return f"`{str(v).lower()}`"
    if isinstance(v, (int, float)):
        return f"`{json.dumps(v)}`"
    if isinstance(v, (list, dict)):
        return f"`{py_compact(v)}`"
    return f"`{v}`"


def toml_value(v):
    if isinstance(v, bool):
        return "true" if v else "false"
    if isinstance(v, (int, float)):
        return json.dumps(v)
    if isinstance(v, str):
        return py_str(v)
    if isinstance(v, dict):
        parts = []
        for key, item in v.items():
            if item is None:
                continue
            bare = key and all(
                c.isascii() and (c.isalnum() or c in "_-") for c in key
            )
            k = key if bare else py_str(key)
            parts.append(f"{k} = {toml_value(item)}")
        if not parts:
            return "{}"
        return "{ " + ", ".join(parts) + " }"
    return py_compact(v)


def leaves(table):
    rows = []
    for row in table["leaves"]:
        rows.append(
            {
                "path": row.get("path", ""),
                "type": row.get("type", ""),
                "default": row.get("default"),
                "wizard": row.get("wizard", "never"),
                "question": row.get("question", ""),
                "default_source": row.get("default_source", ""),
                "doc": row.get("doc", ""),
            }
        )
    return rows


class Node:
    def __init__(self):
        self.leaves = []
        self.tables = []

    def child(self, seg):
        for name, node in self.tables:
            if name == seg:
                return node
        node = Node()
        self.tables.append((seg, node))
        return node


def emit(node, prefix, lines):
    if prefix and node.leaves:
        lines.append("")
        lines.append("[" + ".".join(prefix) + "]")
    for leaf in node.leaves:
        if leaf["doc"]:
            lines.append("# " + " ".join(leaf["doc"].split()))
        key = leaf["path"].rsplit(".", 1)[-1]
        if leaf["default"] is None:
            lines.append(f"# {key} = <unset>   # optional; no default")
        else:
            lines.append(f"{key} = {toml_value(leaf['default'])}")
    for seg, child in node.tables:
        prefix.append(seg)
        emit(child, prefix, lines)
        prefix.pop()


def render_json_schema(table):
    return json.dumps(table["json_schema"], indent=2, sort_keys=True) + "\n"


def wizard_rows(table, include):
    return [
        {
            "path": leaf["path"],
            "type": leaf["type"],
            "default": leaf["default"],
            "tier": leaf["wizard"],
            "question": leaf["question"],
            "default_source": leaf["default_source"],
            "doc": leaf["doc"],
        }
        for leaf in leaves(table)
        if leaf["wizard"] != "never" and include(leaf["wizard"])
    ]


def render_wizard_plan(table, include):
    return json.dumps({"fields": wizard_rows(table, include)}, indent=2) + "\n"


def render_markdown(table):
    lines = list(MARKDOWN_HEADER)
    for leaf in leaves(table):
        lines.append(
            f"| `{leaf['path']}` | {cell(leaf['type'])} | "
            f"{cell(fmt_default(leaf['default']))} | {cell(leaf['wizard'])} | "
            f"{cell(leaf['doc'])} |"
        )
    lines.append("")
    # The file write stores the bare join; the stdout golden carries the one
    # newline println! adds on top.
    return "\n".join(lines)


def render_toml(table):
    lines = list(TOML_HEADER)
    root = Node()
    for leaf in leaves(table):
        segs = leaf["path"].split(".")
        node = root
        for seg in segs[:-1]:
            node = node.child(seg)
        node.leaves.append(leaf)
    emit(root, [], lines)
    lines.append("")
    return "\n".join(lines)


def old_table():
    out = subprocess.run(
        ["git", "-C", str(ROOT), "show", "origin/main:crates/fno/config_schema.json"],
        capture_output=True,
        check=True,
    )
    return json.loads(out.stdout)


def validate(old):
    checks = [
        ("json_schema.stdout", render_json_schema(old), [GOLDENS / "json_schema.stdout"]),
        (
            "wizard_plan.stdout",
            render_wizard_plan(old, lambda _t: True),
            [GOLDENS / "wizard_plan.stdout"],
        ),
        (
            "setup_plan.stdout",
            render_wizard_plan(old, lambda t: t == "always"),
            [GOLDENS / "setup_plan.stdout"],
        ),
        (
            "setup_plan_advanced.stdout",
            render_wizard_plan(old, lambda _t: True),
            [GOLDENS / "setup_plan_advanced.stdout"],
        ),
        (
            "configuration-guide.md",
            render_markdown(old) + "\n",
            [GOLDENS / "markdown.stdout"],
        ),
        (
            "configuration-guide.md (file)",
            render_markdown(old),
            [ROOT / "docs/configuration-guide.md"],
        ),
        (
            "config.example.toml (stdout)",
            render_toml(old) + "\n",
            [GOLDENS / "toml.stdout"],
        ),
        (
            "config.example.toml (file)",
            render_toml(old),
            [
                ROOT / "crates/fno/config.example.toml",
                ROOT / "docs/config.example.toml",
            ],
        ),
    ]
    ok = True
    for name, rendered, targets in checks:
        for target in targets:
            want = target.read_text(encoding="utf-8")
            if rendered != want:
                ok = False
                print(f"MISMATCH {target.relative_to(ROOT)} (render {name})")
                for i, (a, b) in enumerate(zip(rendered.split("\n"), want.split("\n"))):
                    if a != b:
                        print(f"  first diff at line {i + 1}:")
                        print(f"  render: {a[:120]}")
                        print(f"  file:   {b[:120]}")
                        break
                else:
                    print(f"  length differs: render {len(rendered)} file {len(want)}")
    return ok


def write(new):
    outputs = [
        (GOLDENS / "json_schema.stdout", render_json_schema(new)),
        (GOLDENS / "wizard_plan.stdout", render_wizard_plan(new, lambda _t: True)),
        (
            GOLDENS / "setup_plan_advanced.stdout",
            render_wizard_plan(new, lambda _t: True),
        ),
        (GOLDENS / "markdown.stdout", render_markdown(new) + "\n"),
        (ROOT / "docs/configuration-guide.md", render_markdown(new)),
        (GOLDENS / "toml.stdout", render_toml(new) + "\n"),
        (ROOT / "crates/fno/config.example.toml", render_toml(new)),
        (ROOT / "docs/config.example.toml", render_toml(new)),
    ]
    for target, text in outputs:
        target.write_text(text, encoding="utf-8")
        print(f"wrote {target.relative_to(ROOT)}")


def main():
    parser = argparse.ArgumentParser()
    parser.add_argument("--validate", action="store_true")
    parser.add_argument("--write", action="store_true")
    args = parser.parse_args()
    if args.validate:
        sys.exit(0 if validate(old_table()) else 1)
    if args.write:
        if not validate(old_table()):
            print("refusing: the renderer is not byte-faithful on the pre-edit table")
            sys.exit(1)
        write(json.loads(TABLE.read_text(encoding="utf-8")))
        sys.exit(0)
    parser.error("pick --validate or --write")


if __name__ == "__main__":
    main()
